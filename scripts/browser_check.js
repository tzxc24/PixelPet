/* Run explicitly with playwright-cli run-code --filename=scripts/browser_check.js.
   Uses the live configured model for a few short acceptance turns. */
async page => {
  const checks=[],errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const check=(value,label)=>checks.push({label,passed:!!value});
  const ready=()=>page.waitForFunction(()=>!document.querySelector('#chat-form button').disabled,null,{timeout:70000});
  const send=async(text)=>{
    await ready();await page.locator('#message').fill(text);
    const responsePromise=page.waitForResponse(response=>response.url().endsWith('/api/chat/stream'));
    await page.getByRole('button',{name:'发送消息',exact:true}).click();
    const response=await responsePromise;await response.finished();
    const raw=await response.text();await ready();
    const events=raw.split('\n\n').filter(Boolean).map(block=>{const lines=block.split('\n');return [lines[0].slice(7),JSON.parse(lines[1].slice(6))];});
    const done=events.find(([name])=>name==='done')?.[1];
    check(!!done,'chat completes via SSE');
    check(events.some(([name])=>name==='delta'),'incremental text arrives');
    if(!done)throw new Error(JSON.stringify(events));
    check(await page.locator('#state-code').textContent()===done.state,'model emotion/action drives animation');
    return done;
  };
  await page.setViewportSize({width:1280,height:1100});await page.reload();await ready();
  if(await page.locator('#auto-speak').count())await page.locator('#auto-speak').uncheck();
  check((await page.locator('#chat-mode').textContent()).includes('DeepSeek'),'DeepSeek mode displayed');
  await page.locator('#new-chat').click();await ready();
  const first=await send('你好小星，你叫什么名字？');
  check(first.reply.includes('小星'),'real model introduces character');
  await send('请记住，我正在开发 ESP32 AI 桌宠 PixelPet。');
  const firstCid=await page.locator('#conversation-select').inputValue();
  const count=await page.locator('#chat-log .message').count();
  await page.reload();await ready();
  check(await page.locator('#chat-log .message').count()===count,'page reload restores SQLite history');
  await page.locator('#new-chat').click();await ready();
  check(await page.locator('#conversation-select').inputValue()!==firstCid,'new conversation ID');
  const recall=await send('你还记得我最近正在开发什么吗？');
  check(recall.reply.includes('ESP32')||recall.reply.includes('PixelPet'),'cross-conversation memory retrieved');
  const recallCid=await page.locator('#conversation-select').inputValue();
  const failLoad=route=>route.fulfill({status:503,json:{detail:'测试历史加载失败'}});
  await page.route(`**/api/conversations/${firstCid}/messages`,failLoad);
  await page.locator('#conversation-select').selectOption(firstCid);await ready();
  check(await page.locator('#conversation-select').inputValue()===recallCid,'failed history switch restores selection');
  check(await page.locator('#chat-log .message p').last().textContent()===recall.reply,'failed history switch preserves current view');
  await page.unroute(`**/api/conversations/${firstCid}/messages`,failLoad);
  await page.locator('#conversation-select').selectOption(firstCid);await ready();
  check(await page.locator('#chat-log .message').count()===count,'history switch restores original messages');
  await page.locator('#open-memories').click();
  await page.locator('#memory-panel').waitFor({state:'visible'});
  await page.waitForFunction(()=>document.querySelector('#memory-list').textContent.includes('ESP32'));
  check((await page.locator('#memory-list').textContent()).includes('ESP32'),'memory manager shows extracted project');
  await page.locator('#memory-content').fill('浏览器验收测试：蓝色星星纸条');
  await page.locator('#memory-form button').click();
  await page.waitForFunction(()=>document.querySelector('#memory-list').textContent.includes('蓝色星星纸条'));
  const card=page.locator('.memory-card').filter({hasText:'蓝色星星纸条'});
  await card.getByRole('button',{name:'编辑',exact:true}).click();
  await page.locator('#memory-content').fill('浏览器验收测试：绿色星星纸条');
  await page.locator('#memory-form button').click();
  await page.waitForFunction(()=>document.querySelector('#memory-list').textContent.includes('绿色星星纸条'));
  check(!(await page.locator('#memory-list').textContent()).includes('蓝色星星纸条'),'memory edit persisted');
  await page.locator('#memory-query').fill('绿色星星纸条');await page.locator('#search-memories').click();
  await page.waitForTimeout(250);
  check((await page.locator('#memory-list').textContent()).includes('绿色星星纸条'),'memory search');
  await page.locator('.memory-card').filter({hasText:'绿色星星纸条'}).getByRole('button',{name:'删除',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#memory-list').textContent.includes('绿色星星纸条'));
  check(true,'temporary memory deleted');await page.locator('#close-memories').click();
  const failedRefresh=async route=>route.request().method()==='GET'?route.fulfill({status:503,json:{detail:'测试刷新失败'}}):route.continue();
  await page.route('**/api/conversations',failedRefresh);
  const completed=await send('你还记得我吗？');
  check((await page.locator('#chat-log .message p').last().textContent())===completed.reply,'completed answer survives history refresh failure');
  check(!(await page.locator('#chat-log .message').last().getAttribute('class')).includes('failed-message'),'completed answer not marked failed');
  await page.unroute('**/api/conversations',failedRefresh);await page.reload();await ready();
  for(const state of ['IDLE','HAPPY','LISTENING','THINKING','SPEAKING','SHY','SLEEP','SURPRISED']){
    await page.locator(`[data-state="${state}"]`).click();
    await page.waitForFunction(expected=>document.querySelector('#state-code').textContent===expected,state);
    const frames=new Set();
    for(let i=0;i<9;i++){frames.add(await page.locator('#pet').evaluate(canvas=>canvas.toDataURL()));await page.waitForTimeout(120);}
    check(frames.size>1,`${state} animation preserved`);
  }
  const touchPromise=page.waitForResponse(response=>response.url().endsWith('/api/chat/stream'));
  await page.locator('[data-event="touch_start"]').click();
  const touch=await touchPromise;await touch.finished();await ready();
  check((await touch.text()).includes('event: done'),'touch triggers role response');
  await page.locator('[data-event="audio_start"]').click();
  await page.waitForFunction(()=>!document.querySelector('#audio-end').disabled);
  await page.locator('[data-event="audio_end"]').click();
  await page.waitForFunction(()=>document.querySelector('#audio-end').disabled);
  check(true,'simulated recording controls preserved');
  await page.locator('#new-chat').click();await ready();
  const scratch=await page.locator('#conversation-select').inputValue();
  await page.locator('#clear-chat').click();await ready();
  check(await page.locator('#chat-log .message').count()===1,'clear current conversation');
  await page.locator('#delete-chat').click();await ready();
  check(await page.locator(`#conversation-select option[value="${scratch}"]`).count()===0,'delete conversation');
  await page.locator('#conversation-select').selectOption(firstCid);await ready();
  await page.screenshot({path:'D:/PixelPet/output/playwright/deepseek-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile has no horizontal overflow');
  await page.screenshot({path:'D:/PixelPet/output/playwright/deepseek-mobile.png',fullPage:true});
  check(errors.length===0,'no JavaScript runtime errors');
  await page.setViewportSize({width:1280,height:1100});
  return {total:checks.length,checks,failures:checks.filter(item=>!item.passed),errors};
}
